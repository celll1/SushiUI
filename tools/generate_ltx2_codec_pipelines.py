"""Regenerate target-clock pipeline methods from the installed diffusers source."""

import ast
import builtins
import hashlib
from pathlib import Path
import symtable
import sysconfig


ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(sysconfig.get_paths()["purelib"])/"diffusers/pipelines/ltx2"
TARGET = ROOT/"backend/core/models/ltx2/codec_pipelines"
MODULES = {"pipeline_ltx2":"LTX2Pipeline", "pipeline_ltx2_image2video":"LTX2ImageToVideoPipeline",
           "pipeline_ltx2_condition":"LTX2ConditionPipeline"}


class Geometry(ast.NodeTransformer):
    def __init__(self):
        self.counts = self.coords = 0

    def visit_BinOp(self, node):
        if ast.unparse(node) == "(num_frames - 1) // self.vae_temporal_compression_ratio + 1":
            self.counts += 1
            return ast.parse("self._codec_latent_frames(num_frames)", mode="eval").body
        return self.generic_visit(node)

    def visit_Attribute(self, node):
        if ast.unparse(node) == "self.transformer.rope.prepare_video_coords":
            self.coords += 1
            return ast.parse("self._codec_video_coords", mode="eval").body
        return self.generic_visit(node)


def globals_in(table):
    names = {symbol.get_name() for symbol in table.get_symbols() if symbol.is_global() and symbol.is_referenced()}
    for child in table.get_children():
        names.update(globals_in(child))
    return names


def generate(module, class_name, *, write=True):
    source = (SOURCE/(module+".py")).read_text(encoding="utf-8")
    original = next(node for node in ast.parse(source).body if isinstance(node,ast.ClassDef) and node.name == class_name)
    methods = [node for node in original.body if isinstance(node,ast.FunctionDef) and node.name in ("__call__","prepare_latents")]
    patch = Geometry()
    for method in methods:
        if isinstance(method.body[0],ast.Expr) and isinstance(method.body[0].value,ast.Constant) and isinstance(method.body[0].value.value,str):
            method.body.pop(0)
        method.decorator_list = [node for node in method.decorator_list if not isinstance(node,ast.Call)
                                 or ast.unparse(node.func) != "replace_example_docstring"]
        patch.visit(method)
    if (patch.counts,patch.coords) != (2,1):
        raise ValueError(f"Review upstream geometry changes in {module}: {patch.counts}/{patch.coords}")
    body = ast.unparse(ast.Module(body=methods,type_ignores=[]))
    names = sorted(globals_in(symtable.symtable(body,module,"exec"))-set(vars(builtins))-{"xm"})
    imports = f"from diffusers.pipelines.ltx2.{module} import ({', '.join(names)}, {class_name} as NativePipeline)\n"
    license_header = source[:source.index("import copy")]
    output = license_header+f'"""Target-clock methods; generated by tools/generate_ltx2_codec_pipelines.py.\nUpstream SHA256: {hashlib.sha256(source.encode()).hexdigest()}\n"""\n\n'
    output += imports+"from .geometry import CodecGeometry\n\nif XLA_AVAILABLE:\n    from diffusers.pipelines.ltx2."+module+" import xm\n\n"
    output += f"class {class_name}(CodecGeometry, NativePipeline):\n"+"\n".join("    "+line if line else "" for line in body.splitlines())+"\n"
    ast.parse(output)
    if write:
        TARGET.mkdir(parents=True,exist_ok=True)
        (TARGET/(module+".py")).write_text(output,encoding="utf-8")
    return output


if __name__ == "__main__":
    for name,cls in MODULES.items():
        generate(name,cls)
